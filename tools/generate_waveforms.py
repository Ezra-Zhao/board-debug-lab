#!/usr/bin/env python3
"""Generate SYNTHETIC I2C waveform data for Case 01 (SDA stuck low).

This is programmatic simulation only. It is NOT a scope or logic-analyzer
capture, NOT measured from any real board, and must never be presented as
measured data. It exists to demonstrate how a waveform would be read:
where the ACK slot is, what "SDA never releases" looks like against an
expected trace, and which timestamps a debug note should cite.

Outputs:
  data/waveforms/case01_i2c_sda_stuck_low.csv
  data/waveforms/case01_i2c_waveform.png
"""
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "data" / "waveforms"

STEP_US = 0.5
T_END_US = 120.0

# One I2C byte frame: START, 8 data bits (0xA0 = 1010_0000, write addr frame
# invented for this synthetic example), ACK slot, STOP attempt.
# Bit cell = 10 us. SCL low 5 us, high 5 us inside each cell.
FRAME_START_US = 10.0
BIT_US = 10.0
DATA_BITS = [1, 0, 1, 0, 0, 0, 0, 0]


def scl_at(t: float) -> float:
    if t < FRAME_START_US:
        return 1.0
    pos = (t - FRAME_START_US) % BIT_US
    cell = int((t - FRAME_START_US) // BIT_US)
    if cell >= 9:  # after 8 data cells + ACK cell, bus idles
        return 1.0
    return 0.0 if pos < 5.0 else 1.0


def expected_sda_at(t: float) -> float:
    if t < FRAME_START_US:
        return 1.0
    if t < FRAME_START_US + 2.0:
        return 0.0  # START: SDA falls while SCL high (simplified edge placement)
    cell = int((t - FRAME_START_US) // BIT_US)
    if cell < 8:
        return float(DATA_BITS[cell])
    if cell == 8:
        return 0.0  # ACK: receiver pulls SDA low
    return 1.0


def observed_sda_at(t: float) -> float:
    # Fault model: SDA releases for the START edge, then a short / stuck
    # device holds it low for the rest of the frame. Data bits and the ACK
    # slot become indistinguishable -- that ambiguity is the diagnostic point.
    if t < FRAME_START_US + 2.0:
        return expected_sda_at(t)
    return 0.0


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    n = int(T_END_US / STEP_US) + 1
    rows = []
    for i in range(n):
        t = round(i * STEP_US, 3)
        rows.append((t, scl_at(t), expected_sda_at(t), observed_sda_at(t)))

    csv_path = OUT_DIR / "case01_i2c_sda_stuck_low.csv"
    with csv_path.open("w", encoding="utf-8") as f:
        f.write("# SYNTHETIC DATA - generated by tools/generate_waveforms.py\n")
        f.write("# NOT a scope/logic-analyzer capture. NOT measured from any real board.\n")
        f.write("# Frame: START, data byte 0xA0 (synthetic), ACK slot. Bit cell 10 us.\n")
        f.write("time_us,scl,expected_sda,observed_sda_stuck_low\n")
        for t, scl, exp, obs in rows:
            f.write(f"{t:.1f},{scl:.0f},{exp:.0f},{obs:.0f}\n")

    times = [r[0] for r in rows]
    fig, axes = plt.subplots(3, 1, sharex=True, figsize=(11, 5.2))
    fig.suptitle("SYNTHETIC I2C waveform - SDA stuck low (not measured data)", fontsize=11)
    axes[0].plot(times, [r[1] for r in rows], drawstyle="steps-post", color="#1f77b4")
    axes[0].set_ylabel("SCL")
    axes[1].plot(times, [r[2] for r in rows], drawstyle="steps-post", color="#2ca02c")
    axes[1].set_ylabel("SDA expected")
    axes[2].plot(times, [r[3] for r in rows], drawstyle="steps-post", color="#d62728")
    axes[2].set_ylabel("SDA observed\n(stuck low)")
    axes[2].set_xlabel("time (us, synthetic timebase)")
    for ax in axes:
        ax.set_ylim(-0.25, 1.35)
        ax.set_yticks([0, 1])
        ax.grid(True, alpha=0.3)
        ax.axvline(FRAME_START_US, color="gray", linestyle="--", linewidth=0.8)
    ack_t = FRAME_START_US + 8 * BIT_US
    axes[2].annotate("ACK slot: indistinguishable\nbecause SDA never releases",
                     xy=(ack_t + 5, 0.0), xytext=(ack_t - 2, 0.55),
                     arrowprops=dict(arrowstyle="->", color="#d62728"), fontsize=8, color="#d62728")
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    png_path = OUT_DIR / "case01_i2c_waveform.png"
    fig.savefig(png_path, dpi=160)
    plt.close(fig)
    print(f"wrote {csv_path} ({len(rows)} rows)")
    print(f"wrote {png_path}")


if __name__ == "__main__":
    main()
